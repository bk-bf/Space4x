export type IconName = keyof typeof ICONS;

export function iconPath(name: IconName): string {
  let d = '';
  ICONS[name].forEach((r: string, y: number) => {
    for (let x = 0; x < r.length;) {
      if (r[x] !== '#') {
        x++;
        continue;
      }
      let n = 1;
      while (r[x + n] === '#') n++;
      d += `M${x} ${y}h${n}v1h-${n}z`;
      x += n;
    }
  });
  return d;
}
